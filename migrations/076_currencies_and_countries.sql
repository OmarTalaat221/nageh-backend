-- Migration 076: currencies and countries, so a price can be quoted where the student is.
--
-- Until now the platform had exactly one price per course and one currency label ('USD', set by
-- migration 067) that nothing ever chose - a student in Cairo and a student in Riyadh were quoted
-- the same number with the same sign in front of it. These two tables are what a per-country price
-- is hung off: the country the student is in, and the currency that country pays in.
--
-- Reference data only. Nothing here changes a single price. Migration 077 is what adds the prices
-- themselves, and until an admin enters one, every item still sells at its existing price in the
-- base currency.
--
-- The names are not typed by hand. They are generated from the ICU data that ships with Node, in
-- both Arabic and English, so "المملكة العربية السعودية" and "Saudi Arabia" are the same spellings
-- every other piece of software on the user's machine uses. The symbols come from the same place:
-- Arabic gets "رس" for the Saudi riyal, English gets "SAR", rather than both getting the code.
--
-- Re-running this refreshes the names and dial codes (ours to correct) and leaves `is_active`,
-- `sort_order` and a country's `currency_code` alone (an admin's to decide).

-- =================================================================================================
-- 1. Currencies
-- =================================================================================================
--
-- `decimal_digits` is not decoration. A Kuwaiti dinar has three of them and a Japanese yen has
-- none; rounding either one to two places prints a price that is wrong in that country's own
-- terms. It is stored so the dashboards do not each have to guess.

CREATE TABLE IF NOT EXISTS `currencies` (
    `id` BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    `code` CHAR(3) NOT NULL COMMENT 'ISO 4217',
    `name_ar` VARCHAR(120) NOT NULL,
    `name_en` VARCHAR(120) NOT NULL,
    `symbol_ar` VARCHAR(20) NOT NULL,
    `symbol_en` VARCHAR(20) NOT NULL,
    `decimal_digits` TINYINT UNSIGNED NOT NULL DEFAULT 2,
    `is_active` TINYINT(1) NOT NULL DEFAULT 1,
    `sort_order` INT NOT NULL DEFAULT 0,
    `created_at` TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY `uniq_currency_code` (`code`),
    KEY `idx_currency_active` (`is_active`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

