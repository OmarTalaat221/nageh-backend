-- =================================================================================================
-- 2. Countries
-- =================================================================================================
--
-- `iso2` is the join key for everything: it is what Cloudflare's CF-IPCountry header carries and
-- what every geo-IP service returns, so a lookup lands on a row without a name comparison.
--
-- `currency_code` is the country's default, and it is what a price entered for that country is
-- denominated in. It is deliberately not a foreign key to `currencies`: a country whose currency
-- was later deactivated must still keep its own name for it rather than losing the row.
--
-- `sort_order` puts the markets this site actually sells into at the top of every select. The rest
-- follow, sorted by name in whichever language the client asked for.

CREATE TABLE IF NOT EXISTS `countries` (
    `id` BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    `iso2` CHAR(2) NOT NULL COMMENT 'ISO 3166-1 alpha-2, uppercase',
    `name_ar` VARCHAR(150) NOT NULL,
    `name_en` VARCHAR(150) NOT NULL,
    `dial_code` VARCHAR(10) NOT NULL DEFAULT '',
    `currency_code` CHAR(3) NOT NULL COMMENT 'The currency a price for this country is entered in',
    `is_active` TINYINT(1) NOT NULL DEFAULT 1,
    `sort_order` INT NOT NULL DEFAULT 100,
    `created_at` TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY `uniq_country_iso2` (`iso2`),
    KEY `idx_country_active` (`is_active`, `sort_order`),
    KEY `idx_country_currency` (`currency_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

